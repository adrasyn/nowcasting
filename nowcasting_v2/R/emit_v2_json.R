# emit_v2_json.R
# STAGED v2 emit (Phase 5). Produces data/latest_v2.json — a PARALLEL, NON-
# DESTRUCTIVE artifact that does NOT touch the live data/latest.json. The frontend
# cutover (reading latest_v2.json) is gated on James's approval.
#
# Two models, per James's 2026-06-10 decision (headline + toggle):
#   headline = qa_a05_q1_l01     (precision; MAI -> QA U-MIDAS, sel_alpha 0.05, q=1)
#   stress   = umidas_a20_q1_l01 (robustness/big-events; full U-MIDAS, alpha 0.20, q=1)
# Both on panel B3_nab_wmi (exclude AiG). Same MAI engine, different MIDAS step.
#
# Bias-aware CI level-bands from pipeline/seed/ci_params_v2*.json (regenerated by
# compute_ci_params.R off the v2 backtest). yoy = 4-quarter QoQ chain (3 actuals +
# nowcast). v1 comparison pointer read READ-ONLY from the live latest.json.
#
# Usage (from nowcasting_v2/, native Rscript + R_LIBS=pipeline lib):
#   Rscript R/emit_v2_json.R [--fetch]      (default reuses the cached vintage)

